export interface BillingReceiptData {
  receiptNumber: string;
  organizationName: string;
  orgId: string;
  adminEmail: string;
  planLabel: string;
  interval: 'monthly' | 'annual';
  amountInr: number;
  currency: 'INR';
  razorpayOrderId: string;
  razorpayPaymentId: string | null;
  method?: string | null;
  status: string;
  paidAt: string;
  expiresAt?: string | null;
  testMode?: boolean;
}

function fmtDate(iso: string | null | undefined): string {
  if (!iso) return '—';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
}

export async function downloadBillingReceiptPdf(data: BillingReceiptData): Promise<string> {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  // Brand top stripe
  doc.setFillColor(249, 115, 22);
  doc.rect(0, 0, 210, 5, 'F');

  // Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(15, 23, 42);
  doc.text('Khazna AI · Subscription Receipt', 14, 20);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(100, 116, 139);
  doc.text(`Receipt No: ${data.receiptNumber}`, 14, 27);
  doc.text(`Issued: ${fmtDate(data.paidAt)}`, 150, 27);

  if (data.testMode) {
    doc.setFillColor(254, 243, 199);
    doc.roundedRect(14, 32, 182, 9, 1.5, 1.5, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(146, 64, 14);
    doc.text('RAZORPAY TEST MODE RECEIPT — NO REAL FUNDS CHARGED', 18, 38);
  }

  const topY = data.testMode ? 48 : 38;

  // Billed To Box
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(14, topY, 182, 28, 2, 2, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text('BILLED TO ORGANIZATION', 18, topY + 7);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(data.organizationName || data.orgId, 18, topY + 14);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`Organization ID: ${data.orgId} · Admin: ${data.adminEmail}`, 18, topY + 21);

  // Payment Details Table
  const tableY = topY + 36;
  doc.setFillColor(15, 23, 42);
  doc.rect(14, tableY, 182, 9, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(255, 255, 255);
  doc.text('Description', 18, tableY + 6);
  doc.text('Billing Cycle', 112, tableY + 6);
  doc.text('Amount', 168, tableY + 6);

  doc.setFillColor(255, 255, 255);
  doc.setDrawColor(226, 232, 240);
  doc.rect(14, tableY + 9, 182, 14, 'FD');
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(15, 23, 42);
  doc.text(data.planLabel, 18, tableY + 18);
  doc.text(data.interval === 'annual' ? 'Annual (12 Months)' : 'Monthly (1 Month)', 112, tableY + 18);
  doc.setFont('helvetica', 'bold');
  doc.text(`Rs. ${data.amountInr.toLocaleString('en-IN')}`, 168, tableY + 18);

  // Gateway & Reference Metadata
  const metaY = tableY + 32;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(15, 23, 42);
  doc.text('Payment & Verification Details', 14, metaY);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  const rows: Array<[string, string]> = [
    ['Payment Status', data.status.toUpperCase()],
    ['Razorpay Payment ID', data.razorpayPaymentId || 'Pending'],
    ['Razorpay Order ID', data.razorpayOrderId],
    ['Payment Method', data.method ? data.method.toUpperCase() : 'Razorpay Checkout'],
    ['Currency', data.currency],
    ['Premium Valid Through', fmtDate(data.expiresAt)],
  ];

  rows.forEach(([label, value], idx) => {
    const y = metaY + 8 + idx * 7;
    doc.setTextColor(100, 116, 139);
    doc.text(label, 14, y);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 23, 42);
    doc.text(value, 72, y);
    doc.setFont('helvetica', 'normal');
  });

  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text(
    'Generated by Khazna AI Billing Engine. Keep this receipt for your institutional records.',
    14,
    280
  );

  const filename = `Khazna_Receipt_${(data.razorpayPaymentId || data.razorpayOrderId).replace(/[^a-zA-Z0-9_-]/g, '_')}.pdf`;
  doc.save(filename);
  return filename;
}
